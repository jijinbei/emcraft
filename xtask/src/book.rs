//! `cargo xtask book`: builds the site (docs/book) into `target/site`: the landing page at its
//! root and the book (mdBook) under `book/`.
//!
//! The reference pages are not typed: [`GENERATED`] copies the documents the code writes
//! (`docs/features.md`, `docs/oracle.md`) into the book, and the landing's numbers ([`Facts`])
//! are read from them. The built tree gets its search-engine files ([`canonical`], the site map)
//! and is refused when a link in it leads nowhere ([`broken_links`]).
//!
//! `mdbook` is an external program (`$MDBOOK`, else on the `PATH`). The layout follows
//! SolidCraft's book (`cargo xtask book`, `docs/book/seo.sh`; MIT OR Apache-2.0), see
//! ATTRIBUTION.md.

use std::path::{Path, PathBuf};
use std::process::Command;

/// Where the site is served, without a trailing slash.
const SITE: &str = "https://jijinbei.github.io/emcraft";

/// The book's folder, relative to the workspace root.
const BOOK: &str = "docs/book";

/// The pictures' folder, copied into the book as `media/` (without [`SKIPPED_MEDIA`]).
const MEDIA: &str = "docs/media";

/// Pictures the site does not show (the README's animation: the site plays the video).
const SKIPPED_MEDIA: &[&str] = &["walkthrough.gif"];

/// Pages of the built tree that are not content: kept out of search results and of the link
/// check (they repeat or generate the other pages' links).
const NOT_CONTENT: &[&str] = &["404.html", "toc.html", "print.html"];

/// A generated document copied into the book: its file, the page it becomes (under the book's
/// `src`) and the link targets rewritten on the way (`from`, `to`).
struct Generated {
    from: &'static str,
    to: &'static str,
    links: &'static [(&'static str, &'static str)],
}

const GENERATED: &[Generated] = &[
    Generated { from: "docs/features.md", to: "reference/commands.md", links: &[] },
    Generated { from: SAMPLES, to: "reference/samples.md", links: &[] },
    Generated {
        from: "docs/oracle.md",
        to: "verification/results.md",
        links: &[("](../tests/oracle/", "](https://github.com/jijinbei/emcraft/tree/main/tests/oracle/"), ("](verification.md)", "](how.md)")],
    },
];

/// The samples' list, written by `cargo xtask features` ([`samples_page`]).
pub const SAMPLES: &str = "docs/samples.md";

/// A sample's row in [`SAMPLES`] starts with its name in backticks.
const SAMPLE_ROW: &str = "| `";

/// The samples' list as Markdown, from the reply of the `file.templates` command: a table for
/// each group in the reply's order, each sample with what it is, its kinds of analysis and its
/// parameters with their values.
pub fn samples_page(reply: &serde_json::Value) -> Result<String, String> {
    let templates = reply["templates"].as_array().ok_or("file.templates: no `templates` in the reply")?;
    let text = |v: &serde_json::Value| v.as_str().unwrap_or_default().replace('|', "\\|");
    let parameter = |p: &serde_json::Value| format!("`{}` = {} {}", text(&p["name"]), p["value"], text(&p["unit"])).trim_end().to_owned();
    let list = |v: &serde_json::Value, item: &dyn Fn(&serde_json::Value) -> String| {
        v.as_array().map_or_default(|a| a.iter().map(item).collect::<Vec<_>>().join(", "))
    };
    let mut groups: Vec<(String, Vec<String>)> = Vec::new();
    for t in templates {
        let group = text(&t["group"]);
        let row = format!(
            "{SAMPLE_ROW}{}` | {} | {} | {} |",
            text(&t["name"]),
            text(&t["label"]),
            list(&t["kinds"], &text),
            list(&t["parameters"], &parameter)
        );
        match groups.iter_mut().find(|(g, _)| *g == group) {
            Some((_, rows)) => rows.push(row),
            None => groups.push((group, vec![row])),
        }
    }
    let intro = format!(
        "# Samples\n\nGenerated by `cargo xtask features` (the `file.templates` command). The {} models the start page opens, by what they model. \
         Open one with `emcraft --sample NAME`, solve it with `emcraft-cli sample NAME`, or from a script with `file.sample`; \
         each parameter is a variable of the model (`project.variable` changes it and rebuilds the model).\n",
        templates.len()
    );
    let tables = groups.iter().map(|(group, rows)| {
        let title: String = group.chars().take(1).flat_map(char::to_uppercase).chain(group.chars().skip(1)).collect();
        format!("\n## {title}\n\n| Sample | What it is | Analyses | Parameters |\n|---|---|---|---|\n{}\n", rows.join("\n"))
    });
    Ok(std::iter::once(intro).chain(tables).collect())
}

/// The numbers the landing page shows, as written by the generated documents.
#[derive(Debug, PartialEq, Eq)]
struct Facts {
    /// Verified quantities that pass, and all of them (`docs/oracle.md`).
    passed: String,
    quantities: String,
    /// Commands (`docs/features.md`).
    commands: usize,
    /// Samples ([`SAMPLES`]).
    samples: usize,
}

/// Reads the [`Facts`] from the texts of `docs/oracle.md`, `docs/features.md` and [`SAMPLES`].
fn facts(oracle: &str, features: &str, samples: &str) -> Result<Facts, String> {
    let line =
        oracle.lines().find(|l| l.ends_with("quantities pass.**")).ok_or("docs/oracle.md: no `N of M quantities pass` line (cargo xtask oracle)")?;
    let mut numbers = line.split(|c: char| !c.is_ascii_digit()).filter(|w| !w.is_empty());
    let (passed, quantities) = numbers.next().zip(numbers.next()).ok_or_else(|| format!("docs/oracle.md: no two numbers in `{line}`"))?;
    let commands = features.lines().filter(|l| l.starts_with("## `")).count();
    if commands == 0 {
        return Err("docs/features.md: no commands (cargo xtask features)".into());
    }
    let samples = samples.lines().filter(|l| l.starts_with(SAMPLE_ROW)).count();
    if samples == 0 {
        return Err(format!("{SAMPLES}: no samples (cargo xtask features)"));
    }
    Ok(Facts { passed: passed.to_owned(), quantities: quantities.to_owned(), commands, samples })
}

/// The landing page with its `{{passed}}`, `{{quantities}}`, `{{commands}}` and `{{samples}}` filled in; a
/// placeholder left over is an error.
fn filled(landing: &str, facts: &Facts) -> Result<String, String> {
    let page = landing
        .replace("{{passed}}", &facts.passed)
        .replace("{{quantities}}", &facts.quantities)
        .replace("{{commands}}", &facts.commands.to_string())
        .replace("{{samples}}", &facts.samples.to_string());
    match page.find("{{") {
        Some(at) => Err(format!("the landing page has an unknown placeholder: {}", page[at..].chars().take(24).collect::<String>())),
        None => Ok(page),
    }
}

/// The address a page of the built tree is known by (`page` relative to the site's root, with
/// `/`): a folder's `index.html` is the folder, and the book's introduction is the book.
fn canonical(page: &str) -> String {
    let path = match page {
        "book/introduction.html" => "book/",
        _ => page.strip_suffix("index.html").unwrap_or(page),
    };
    format!("{SITE}/{path}")
}

/// The link targets of a page: the values of its `href` and `src` attributes.
fn links(html: &str) -> Vec<&str> {
    ["href=\"", "src=\""].iter().flat_map(|attr| html.split(attr).skip(1).filter_map(|rest| rest.split('"').next())).collect()
}

/// The file a link names inside the built tree, or `None` for a link that leaves it (another
/// site, a mail address, a place on the same page).
fn local_target(link: &str) -> Option<&str> {
    let file = link.split(['#', '?']).next().unwrap_or(link);
    let leaves = file.is_empty() || file.starts_with('/') || file.contains(':');
    (!leaves).then_some(file)
}

/// Markdown whose `<` outside code spans are written `&lt;`: a generated document's `s<out><in>`
/// is text, where a browser would take it for tags and drop it.
fn angles_escaped(markdown: &str) -> String {
    markdown
        .split('`')
        .enumerate()
        .map(|(i, part)| if i % 2 == 0 { part.replace('<', "&lt;") } else { part.to_owned() })
        .collect::<Vec<_>>()
        .join("`")
}

fn read(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

fn write(path: &Path, text: &str) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}

/// The files under `dir`, sorted (so what is written from them is the same on every run).
fn files(dir: &Path) -> Result<Vec<PathBuf>, String> {
    let mut entries: Vec<PathBuf> =
        std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?.filter_map(|e| e.ok().map(|e| e.path())).collect();
    entries.sort();
    let mut out = Vec::new();
    for path in entries {
        if path.is_dir() {
            out.extend(files(&path)?);
        } else {
            out.push(path);
        }
    }
    Ok(out)
}

/// Copies the files under `from` to the same places under `to`, except those named in `skip`.
fn copy_tree(from: &Path, to: &Path, skip: &[&str]) -> Result<(), String> {
    for file in files(from)? {
        let Ok(inside) = file.strip_prefix(from) else { continue };
        if skip.iter().any(|s| inside == Path::new(s)) {
            continue;
        }
        let target = to.join(inside);
        if let Some(dir) = target.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        }
        std::fs::copy(&file, &target).map_err(|e| format!("{} → {}: {e}", file.display(), target.display()))?;
    }
    Ok(())
}

/// Writes the book's generated pages and pictures (git-ignored) and returns the [`Facts`].
fn generate(root: &Path) -> Result<Facts, String> {
    let src = root.join(BOOK).join("src");
    for page in GENERATED {
        let text = page.links.iter().fold(read(&root.join(page.from))?, |text, (from, to)| text.replace(from, to));
        write(&src.join(page.to), &angles_escaped(&text))?;
    }
    copy_tree(&root.join(MEDIA), &src.join("media"), SKIPPED_MEDIA)?;
    facts(&read(&root.join("docs/oracle.md"))?, &read(&root.join("docs/features.md"))?, &read(&root.join(SAMPLES))?)
}

/// `mdbook <verb>` on the book.
fn mdbook(root: &Path, verb: &str) -> Result<(), String> {
    let program = std::env::var("MDBOOK").unwrap_or_else(|_| "mdbook".into());
    let status = Command::new(&program).arg(verb).arg(root.join(BOOK)).status().map_err(|e| {
        format!("{program}: {e}\nmdBook builds the book: `cargo binstall mdbook`, or a release of {MDBOOK_RELEASES}; $MDBOOK names it when it is not on the PATH")
    })?;
    if status.success() { Ok(()) } else { Err(format!("mdbook {verb} failed ({status})")) }
}

const MDBOOK_RELEASES: &str = "https://github.com/rust-lang/mdBook/releases";

/// A page's path relative to the site's root, with `/`.
fn page_name(site: &Path, page: &Path) -> String {
    page.strip_prefix(site).unwrap_or(page).components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/")
}

fn is_content(name: &str) -> bool {
    !NOT_CONTENT.iter().any(|n| name.rsplit('/').next() == Some(n))
}

/// Gives each page its canonical address (or keeps it out of search results) and writes
/// `sitemap.xml` and `robots.txt`.
fn search_engine_files(site: &Path, pages: &[PathBuf]) -> Result<(), String> {
    let mut addresses = Vec::new();
    for page in pages {
        let name = page_name(site, page);
        let html = read(page)?;
        let tag = if !is_content(&name) {
            "<meta name=\"robots\" content=\"noindex\">".to_owned()
        } else if html.contains("rel=\"canonical\"") {
            continue;
        } else {
            let address = canonical(&name);
            if !addresses.contains(&address) {
                addresses.push(address.clone());
            }
            format!("<link rel=\"canonical\" href=\"{address}\">")
        };
        write(page, &html.replacen("</head>", &format!("{tag}</head>"), 1))?;
    }
    let urls: String = addresses.iter().map(|a| format!("  <url><loc>{a}</loc></url>\n")).collect();
    write(
        &site.join("sitemap.xml"),
        &format!("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n{urls}</urlset>\n"),
    )?;
    write(&site.join("robots.txt"), &format!("User-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n"))
}

/// The links of the content pages that name a file the built tree does not have, as
/// `page: link`.
fn broken_links(site: &Path, pages: &[PathBuf]) -> Result<Vec<String>, String> {
    let mut broken = Vec::new();
    for page in pages {
        let name = page_name(site, page);
        if !is_content(&name) {
            continue;
        }
        let html = read(page)?;
        let dir = page.parent().unwrap_or(site);
        for link in links(&html) {
            let Some(file) = local_target(link) else { continue };
            let target = dir.join(file);
            let found = if target.is_dir() { target.join("index.html").is_file() } else { target.is_file() };
            if !found {
                broken.push(format!("{name}: {link}"));
            }
        }
    }
    Ok(broken)
}

/// Puts the site together in `target/site` from the built book and the landing page.
fn assemble(root: &Path, facts: &Facts) -> Result<PathBuf, String> {
    let site = root.join("target/site");
    if site.exists() {
        std::fs::remove_dir_all(&site).map_err(|e| format!("{}: {e}", site.display()))?;
    }
    copy_tree(&root.join("target/book"), &site.join("book"), &[])?;
    write(&site.join("index.html"), &filled(&read(&root.join(BOOK).join("site/index.html"))?, facts)?)?;
    let pages: Vec<PathBuf> = files(&site)?.into_iter().filter(|f| f.extension().is_some_and(|e| e == "html")).collect();
    let broken = broken_links(&site, &pages)?;
    if !broken.is_empty() {
        return Err(format!("{} link(s) of the site lead nowhere:\n  {}", broken.len(), broken.join("\n  ")));
    }
    search_engine_files(&site, &pages)?;
    Ok(site)
}

/// `cargo xtask book [--serve]`: builds the site; `--serve` instead serves the book alone and
/// rebuilds it as its pages change (`mdbook serve`).
pub fn run(root: &Path, args: &[&str]) -> Result<(), String> {
    let serve = match args {
        [] => false,
        ["--serve"] => true,
        other => return Err(format!("book: unknown arguments `{}`", other.join(" "))),
    };
    let facts = generate(root)?;
    if serve {
        return mdbook(root, "serve");
    }
    mdbook(root, "build")?;
    let site = assemble(root, &facts)?;
    println!(
        "book: {} ({} of {} quantities, {} commands, {} samples)",
        site.display(),
        facts.passed,
        facts.quantities,
        facts.commands,
        facts.samples
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_facts_are_read_from_the_generated_documents() {
        let oracle = "# Verification oracle\n\n**585 of 586 quantities pass.**\n";
        let features = "# Commands\n\n## `a.b` — A\n\ntext\n\n## `c.d` — C\n";
        let samples = "# Samples\n\n| Sample | What it is |\n|---|---|\n| `a` | A |\n";
        assert_eq!(facts(oracle, features, samples), Ok(Facts { passed: "585".into(), quantities: "586".into(), commands: 2, samples: 1 }));
        assert!(facts("nothing", features, samples).is_err());
        assert!(facts(oracle, "# Commands\n", samples).is_err());
        assert!(facts(oracle, features, "# Samples\n").is_err());
    }

    #[test]
    fn the_landing_takes_the_facts_and_refuses_an_unknown_placeholder() {
        let facts = Facts { passed: "3".into(), quantities: "4".into(), commands: 5, samples: 6 };
        assert_eq!(filled("{{passed}}/{{quantities}}, {{commands}}, {{samples}}", &facts).as_deref(), Ok("3/4, 5, 6"));
        assert!(filled("{{sample}}", &facts).is_err());
    }

    #[test]
    fn the_samples_are_listed_by_group_with_their_parameters() {
        let reply = serde_json::json!({"templates": [
            {"group": "filters", "kinds": ["frequency", "time_domain"], "label": "A filter", "name": "highpass",
             "parameters": [{"name": "a", "unit": "mm", "value": 22.86}, {"name": "er", "unit": "", "value": 2.0}]},
            {"group": "antennas", "kinds": ["radiation"], "label": "A dipole", "name": "dipole", "parameters": []},
            {"group": "filters", "kinds": ["frequency"], "label": "Another", "name": "iris-bandpass", "parameters": []},
        ]});
        let page = samples_page(&reply).unwrap_or_default();
        assert!(page.contains("The 3 models"));
        assert!(page.contains("| `highpass` | A filter | frequency, time_domain | `a` = 22.86 mm, `er` = 2.0 |"));
        let (filters, antennas) = (page.find("## Filters").unwrap_or(usize::MAX), page.find("## Antennas").unwrap_or(0));
        assert!(filters < antennas && page.find("`iris-bandpass`").is_some_and(|at| at < antennas));
        assert!(samples_page(&serde_json::json!({})).is_err());
    }

    #[test]
    fn an_angle_bracket_outside_code_is_text() {
        assert_eq!(angles_escaped("S as s<out><in>, `template:<file>` and a < b"), "S as s&lt;out>&lt;in>, `template:<file>` and a &lt; b");
    }

    #[test]
    fn a_folder_index_is_known_by_its_folder() {
        assert_eq!(canonical("index.html"), format!("{SITE}/"));
        assert_eq!(canonical("book/index.html"), format!("{SITE}/book/"));
        assert_eq!(canonical("book/introduction.html"), format!("{SITE}/book/"));
        assert_eq!(canonical("book/start/install.html"), format!("{SITE}/book/start/install.html"));
    }

    #[test]
    fn only_links_into_the_tree_are_checked() {
        let html = r##"<a href="start/install.html#linux">i</a><img src="media/a.png"><a href="https://example.org/x">x</a><a href="#top">t</a>"##;
        let local: Vec<&str> = links(html).into_iter().filter_map(local_target).collect();
        assert_eq!(local, ["start/install.html", "media/a.png"]);
    }
}
